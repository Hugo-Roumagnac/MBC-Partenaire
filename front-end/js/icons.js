// Injecte le sprite <symbol> dans le document (une seule fois).
export function injecterIcones() {
  if (document.getElementById("mbc-icons")) return;
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.id = "mbc-icons";
  svg.setAttribute("aria-hidden", "true");
  svg.style.display = "none";
  svg.innerHTML = Object.entries(PATHS).map(([n, d]) => `<symbol id="i-${n}" viewBox="0 0 24 24">${d}</symbol>`).join("");
  document.body.prepend(svg);
}

